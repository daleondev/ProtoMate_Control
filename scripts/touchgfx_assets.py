#!/usr/bin/env python3
"""Run the pinned SDK's Linux converters; keep generated/vendor files out of src/."""
import argparse
import os
from pathlib import Path
import shutil
import subprocess


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--sdk', type=Path, required=True)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--gems', type=Path)
    args = parser.parse_args()
    sdk, source, output = args.sdk.resolve(), args.source.resolve(), args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source / 'texts.xml', output / 'texts.xml')
    shutil.copy2(sdk / 'framework/tools/textconvert/schema/texts.xsd', output / 'texts.xsd')
    environment = os.environ.copy()
    if args.gems and args.gems.is_dir():
        environment['GEM_PATH'] = str(args.gems.resolve()) + os.pathsep + environment.get('GEM_PATH', '')
    subprocess.run([
        'ruby', str(sdk / 'framework/tools/textconvert/main.rb'), str(output / 'texts.xml'),
        str(sdk / 'framework/tools/fontconvert/build/linux/fontconvert.out'),
        str(output / 'fonts'), str(output / 'texts'), str(source / 'fonts'), str(source),
        'yes', 'A4', 'RGB565',
    ], env=environment, check=True)
    raster=output/'raster'
    shutil.rmtree(raster, ignore_errors=True)
    raster.mkdir(exist_ok=True)
    for path in (source/'images').glob('*.svg'):
        subprocess.run(['rsvg-convert', '-o', str(raster/(path.stem+'.png')), str(path)], check=True)
    for path in (source/'images').glob('*.png'):
        shutil.copy2(path,raster/path.name)
    shutil.rmtree(output/'images', ignore_errors=True)
    subprocess.run([str(sdk / 'framework/tools/imageconvert/build/linux/imageconvert.out'),
                    '-r', str(raster), '-w', str(output/'images'), '-c', str(source/'images.json')], check=True)
    sources = sorted(path for path in (output / 'fonts/src').glob('*.cpp')
                     if path.name in ('GeneratedFont.cpp', 'ApplicationFontProvider.cpp', 'CompressedFontCache.cpp')
                     or path.name.startswith(('Font_', 'Kerning_', 'Table_')))
    sources += sorted((output / 'texts/src').glob('*.cpp'))
    sources += sorted((output/'images/src').rglob('*.cpp'))
    # Linked bitmap fonts only: unused cache/vector/unmapped support is omitted.
    # All symbols in this output are font/language-qualified. One
    # translation unit gives CMake a stable output even when the glyph set changes.
    (output / 'Assets.cpp').write_text('// Generated by touchgfx_assets.py\n' + ''.join(
        f'#include "{path.relative_to(output).as_posix()}"\n' for path in sources))


if __name__ == '__main__':
    main()
