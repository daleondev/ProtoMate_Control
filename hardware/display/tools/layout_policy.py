"""Common adapter layout contract; manufacturer limits and house rules differ.

The authoritative boards are never regenerated by this module. Applying the
ground policy is explicit, and refuses boards that still route on an inner layer.
"""
import argparse
import hashlib
import json
import tempfile
from decimal import Decimal, InvalidOperation
from pathlib import Path

import pcbnew as k

from sexpr import parse, children, child, property_value

k.SwigPyIterator.next = k.SwigPyIterator.__next__
SIGNAL_LAYERS = (k.F_Cu, k.B_Cu)
REFERENCE_LAYERS = (k.In1_Cu, k.In2_Cu)
COPPER_LAYERS = (k.F_Cu, k.In1_Cu, k.In2_Cu, k.B_Cu)
SOURCES = {
    'fabrication': 'https://community.aisler.net/t/4-layer-35-m-enig-design-rules/3733',
    'stackup': 'https://community.aisler.net/t/4-layers-1-6mm-35-m-stackup/5457',
    'return_paths': 'https://www.ti.com/lit/an/spraar7j/spraar7j.pdf#page=6',
    'efuse': 'https://www.ti.com/lit/ds/symlink/tps2660.pdf',
    'ldo': 'https://www.ti.com/lit/ds/symlink/tps7a91.pdf',
}
# These are workmanship screening thresholds, NOT AISLER or IPC requirements.
ANGLE_TOLERANCE_DEG = .1
SHORT_SEGMENT_WIDTHS = 2
TILE_MM = 20
TILE_OVERLAP_MM = 2
PIXELS_PER_MM = 80
# Shared fabrication-safe fanout minimum; board defaults may use larger vias.
# AISLER HD permits 0.25 mm holes / 0.10 mm rings. We keep 0.15 mm via rings.
MIN_VIA_DRILL_MM = .25
MIN_VIA_DIAMETER_MM = .55


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def normalized(value):
    """Ignore numeric spelling/whitespace when KiCad rewrites a saved board."""
    if isinstance(value, list):
        return [normalized(x) for x in value]
    try:
        return str(Decimal(value).normalize())
    except InvalidOperation:
        return value


def protected_content(path):
    """Freeze complete footprints and board graphics, including user silkscreen.

    Routing, zones, title-block revision and cached fill may change. Footprint
    positions alone are not sufficient: pads, text and models are also protected.
    """
    root = parse(Path(path).read_text())
    items = children(root, 'footprint') + [n for n in root if isinstance(n, list)
                                         and n and n[0].startswith(('gr_', 'dimension'))]
    return sorted((normalized(n) for n in items), key=lambda n: json.dumps(n))


def capture(path, output):
    output = Path(output)
    if output.exists():
        raise RuntimeError(f'Refusing to replace placement baseline: {output}')
    output.parent.mkdir(parents=True, exist_ok=True)
    content = protected_content(path)
    output.write_text(json.dumps(dict(source_sha256=sha256(path),
        protected_sha256=hashlib.sha256(json.dumps(content).encode()).hexdigest(),
        protected_item_count=len(content)), indent=2) + '\n')


def check_protected(path, baseline):
    expected = json.loads(Path(baseline).read_text())
    actual = protected_content(path)
    for change in expected.get('allowed_thermal_angles', []):
        index = next((i for i,n in enumerate(actual) if n[0] == 'footprint'
                      and child(n, 'uuid') == ['uuid', change['uuid']]), None)
        if index is not None and actual[index] == change['after']:
            actual[index] = change['before']
    for change in expected.get('allowed_placement_changes', []):
        index = next((i for i,n in enumerate(actual) if n[0] == 'footprint'
                      and child(n, 'uuid') == ['uuid', change['uuid']]), None)
        if index is not None and actual[index] == change['after']:
            actual[index] = change['before']
    # Reconstruct only individually authorized silk deletions. The original
    # fingerprint remains unchanged, so a pad, footprint or outline edit cannot
    # hide behind permission to remove obstructing text.
    for removal in sorted(expected.get('allowed_silkscreen_removals', []), key=lambda r: r['index']):
        parent = actual
        if removal['footprint_uuid'] is not None:
            parent = next((n for n in actual if n[0] == 'footprint'
                           and child(n, 'uuid') == ['uuid', removal['footprint_uuid']]), None)
            if parent is None:
                raise RuntimeError('Protected footprint missing')
        node = removal['node']
        if not any(isinstance(n, list) and child(n, 'uuid') == child(node, 'uuid') for n in parent):
            parent.insert(removal['index'], node)
    actual.sort(key=lambda n: json.dumps(n))
    matches = (actual == expected['protected'] if 'protected' in expected else
               hashlib.sha256(json.dumps(actual).encode()).hexdigest() == expected['protected_sha256'])
    if not matches:
        raise RuntimeError('Protected footprints, mechanics or user graphics changed')


def allow_silkscreen_removal(path, baseline, item_uuid, reason):
    """Record one removal under the user's explicit silk-removal authorization.

    Call before deleting the item. Copper, fabrication graphics, references and
    mechanics cannot be authorized through this narrowly scoped operation.
    """
    if len(reason.strip()) < 20:
        raise ValueError('Describe the concrete obstruction requiring removal')
    check_protected(path, baseline)
    content = protected_content(path)
    matches = []
    for index, node in enumerate(content):
        if child(node, 'uuid') == ['uuid', item_uuid]:
            matches.append((None, index, node))
        if node[0] == 'footprint':
            matches.extend((child(node, 'uuid')[1], i, n) for i, n in enumerate(node) if isinstance(n, list)
                           and child(n, 'uuid') == ['uuid', item_uuid])
    if len(matches) != 1:
        raise ValueError('Expected one existing graphic with this UUID')
    parent_uuid, index, node = matches[0]
    if (not node[0].startswith(('gr_', 'fp_'))
            or child(node, 'layer') not in (['layer', 'F.SilkS'], ['layer', 'B.SilkS'])):
        raise ValueError('Only silkscreen graphics may be removed')
    if node[0] == 'fp_text' and node[1] in ('reference', 'value'):
        raise ValueError('Do not remove component identification through this helper')
    baseline = Path(baseline)
    record = json.loads(baseline.read_text())
    removals = record.setdefault('allowed_silkscreen_removals', [])
    if any(child(r['node'], 'uuid') == ['uuid', item_uuid] for r in removals):
        raise ValueError('This removal is already recorded')
    if parent_uuid:
        # Earlier authorized deletions may already be absent in this input.
        removed_before = sorted(r['index'] for r in removals if r['footprint_uuid'] == parent_uuid
                                and not any(child(n, 'uuid') == child(r['node'], 'uuid')
                                            for n in next(x for x in content if child(x, 'uuid') == ['uuid', parent_uuid])
                                            if isinstance(n, list)))
        for previous_index in removed_before:
            if previous_index <= index:
                index += 1
    removals.append(dict(footprint_uuid=parent_uuid, index=index, node=node, reason=reason,
                         authorization='User: you can remove the silkscreen if needed'))
    baseline.write_text(json.dumps(record, indent=2) + '\n')


def record_placement_change(source, result, baseline, placements, reason):
    """Validate and record explicit (x, y, degrees) moves, not arbitrary edits.

    The user allows component relocation. Reproduce those moves independently
    with KiCad, compare complete footprints/graphics, and retain the original
    fingerprint. Pad geometry, nets, models and mechanics remain protected.
    """
    if len(reason.strip()) < 20 or not placements:
        raise ValueError('Provide explicit placements and their routing justification')
    check_protected(source, baseline)
    before = protected_content(source)
    board = k.LoadBoard(str(source))
    footprints = {f.GetReference(): f for f in board.GetFootprints()}
    for reference, (x, y, degrees) in placements.items():
        if reference not in footprints:
            raise ValueError('Unknown reference: '+reference)
        f = footprints[reference]
        f.SetOrientationDegrees(degrees)
        f.SetPosition(k.VECTOR2I(k.FromMM(x), k.FromMM(y)))
    with tempfile.TemporaryDirectory(prefix='adapter-placement-') as directory:
        path = Path(directory)/Path(source).name
        k.SaveBoard(str(path), board)
        expected = protected_content(path)
    actual = protected_content(result)
    if actual != expected:
        raise RuntimeError('Result contains changes beyond the specified placement transforms')
    baseline = Path(baseline)
    record = json.loads(baseline.read_text())
    changes = record.setdefault('allowed_placement_changes', [])
    for reference, placement in placements.items():
        original = next(n for n in before if n[0] == 'footprint' and property_value(n, 'Reference') == reference)
        proposed = next(n for n in actual if n[0] == 'footprint' and property_value(n, 'Reference') == reference)
        uid = child(original, 'uuid')[1]
        previous = next((c for c in changes if c['uuid'] == uid), None)
        if previous:
            previous.update(after=proposed, placement_mm_degrees=placement, reason=reason)
        else:
            changes.append(dict(reference=reference, uuid=uid, before=original, after=proposed,
                placement_mm_degrees=placement, reason=reason,
                authorization='User: if needed, you can change placement'))
    baseline.write_text(json.dumps(record, indent=2)+'\n')
    check_protected(result, baseline)


def record_thermal_angles(source, result, baseline, angles, reason):
    """Record only orthogonal/diagonal thermal-spoke orientation changes.

    This changes the direction of the relief, never the pad, hole, gap, spoke
    width or required spoke count. Fresh-fill DRC still verifies every relief.
    """
    if len(reason.strip()) < 20 or not angles or any(a not in (0,45) for a in angles.values()):
        raise ValueError('Specify 0/45-degree thermal angles and their justification')
    check_protected(source, baseline)
    before = protected_content(source)
    board = k.LoadBoard(str(source))
    pads = {(f.GetReference(),p.GetNumber()):p for f in board.GetFootprints() for p in f.Pads()}
    for key, angle in angles.items():
        if key not in pads or pads[key].GetNetname() != 'GND':
            raise ValueError('Expected an existing ground pad')
        pads[key].SetThermalSpokeAngleDegrees(angle)
    with tempfile.TemporaryDirectory(prefix='adapter-thermal-') as directory:
        path = Path(directory)/Path(source).name
        k.SaveBoard(str(path),board)
        expected = protected_content(path)
    actual = protected_content(result)
    if actual != expected:
        raise RuntimeError('Result contains changes beyond the specified thermal-spoke angles')
    baseline = Path(baseline)
    record = json.loads(baseline.read_text())
    changes = record.setdefault('allowed_thermal_angles', [])
    for reference in sorted({key[0] for key in angles}):
        original = next(n for n in before if n[0] == 'footprint' and property_value(n,'Reference') == reference)
        proposed = next(n for n in actual if n[0] == 'footprint' and property_value(n,'Reference') == reference)
        changes.append(dict(reference=reference,uuid=child(original,'uuid')[1],before=original,after=proposed,
            angles={pad:angle for (ref,pad),angle in angles.items() if ref==reference},reason=reason))
    baseline.write_text(json.dumps(record,indent=2)+'\n')
    check_protected(result,baseline)


def apply_ground_planes(board):
    """Preserve special-purpose copper; install the same GND policy on both PCBs."""
    routed = [t for t in board.GetTracks() if not isinstance(t, k.PCB_VIA)
              and t.GetLayer() in REFERENCE_LAYERS]
    if routed:
        raise RuntimeError(f'Inner routing must be removed first ({len(routed)} segments)')
    if board.GetCopperLayerCount() != 4:
        raise RuntimeError('This policy requires four copper layers')
    for layer in REFERENCE_LAYERS:
        board.SetLayerType(layer, k.LT_POWER)
    for layer in SIGNAL_LAYERS:
        board.SetLayerType(layer, k.LT_SIGNAL)
    for via in board.GetTracks():
        if isinstance(via, k.PCB_VIA):
            via.SetFrontTentingMode(k.TENTING_MODE_NOT_TENTED)
            via.SetBackTentingMode(k.TENTING_MODE_NOT_TENTED)
    template = next(z for z in board.Zones() if not z.GetIsRuleArea()
                    and z.GetNetname() == 'GND' and z.GetLayer() == k.In1_Cu)
    for layer in COPPER_LAYERS:
        zones = [z for z in board.Zones() if not z.GetIsRuleArea()
                 and z.GetNetname() == 'GND' and z.GetLayer() == layer]
        if not zones:
            zone = k.Cast_to_ZONE(template.Duplicate(False))
            zone.SetLayer(layer)
            board.Add(zone)
            zones = [zone]
        if len(zones) != 1:
            raise RuntimeError(f'Expected one board-wide GND zone on {board.GetLayerName(layer)}')
        zone = zones[0]
        zone.SetZoneName('GND reference' if layer in REFERENCE_LAYERS else 'Stitched GND fill')
        zone.SetMinThickness(k.FromMM(.15))
        zone.SetLocalClearance(k.FromMM(.15))
        zone.SetAssignedPriority(0)
        zone.SetIslandRemovalMode(k.ISLAND_REMOVAL_MODE_ALWAYS)
        zone.SetPadConnection(k.ZONE_CONNECTION_THT_THERMAL)
        zone.SetThermalReliefGap(k.FromMM(.25))
        zone.SetThermalReliefSpokeWidth(k.FromMM(.30))
    # Never merge PWR_RTN into GND or substitute a global power plane.
    for zone in board.Zones():
        if not zone.GetIsRuleArea() and zone.GetNetname() == 'PWR_RTN':
            zone.SetAssignedPriority(1)
        if not zone.GetIsRuleArea() and zone.GetLayer() in REFERENCE_LAYERS:
            if zone.GetNetname() != 'GND':
                raise RuntimeError('Non-GND inner-layer zone violates reference-plane policy')


def validate_policy(path, baseline):
    """Read-only release gate; electrical DRC and region inspection are separate."""
    check_protected(path, baseline)
    board = k.LoadBoard(str(path))
    errors = []
    if board.GetCopperLayerCount() != 4:
        errors.append('Expected four copper layers')
    inner_tracks = [t.m_Uuid.AsString() for t in board.GetTracks()
                    if not isinstance(t, k.PCB_VIA) and t.GetLayer() in REFERENCE_LAYERS]
    if inner_tracks:
        errors.append(f'{len(inner_tracks)} track segments on reserved reference planes')
    for via in board.GetTracks():
        if not isinstance(via, k.PCB_VIA):
            continue
        if via.GetViaType() != k.VIATYPE_THROUGH:
            errors.append('Only through-vias are permitted')
        if (via.GetDrillValue() < k.FromMM(MIN_VIA_DRILL_MM)
                or via.GetWidth(k.F_Cu) < k.FromMM(MIN_VIA_DIAMETER_MM)):
            errors.append('Via below the shared fanout minimum')
        if (via.GetFrontTentingMode() != k.TENTING_MODE_NOT_TENTED
                or via.GetBackTentingMode() != k.TENTING_MODE_NOT_TENTED):
            errors.append('Via mask treatment must explicitly be exposed on both sides')
    zones = {}
    for layer in COPPER_LAYERS:
        ground = [z for z in board.Zones() if not z.GetIsRuleArea()
                  and z.GetLayer() == layer and z.GetNetname() == 'GND']
        zones[board.GetLayerName(layer)] = len(ground)
        if len(ground) != 1:
            errors.append(f'{board.GetLayerName(layer)} requires one board-wide GND zone')
            continue
        zone = ground[0]
        if zone.GetIslandRemovalMode() != k.ISLAND_REMOVAL_MODE_ALWAYS:
            errors.append(f'{board.GetLayerName(layer)} must remove unconnected islands')
        if layer in REFERENCE_LAYERS:
            if board.GetLayerType(layer) != k.LT_POWER:
                errors.append(f'{board.GetLayerName(layer)} must be a plane, not a routable signal layer')
            if zone.GetFilledPolysList(layer).OutlineCount() != 1:
                errors.append(f'{board.GetLayerName(layer)} is unfilled or has disconnected reference regions')
    for zone in board.Zones():
        if not zone.GetIsRuleArea() and zone.GetLayer() in REFERENCE_LAYERS and zone.GetNetname() != 'GND':
            errors.append('Non-GND zone on a reserved reference plane')
    report = dict(result='FAIL' if errors else 'PASS', source_sha256=sha256(path),
                  protected_baseline_sha256=sha256(baseline), ground_zones=zones,
                  inner_track_uuids=inner_tracks, errors=errors, sources=SOURCES,
                  scope='Architecture and protected-content checks; not electrical, visual or physical sign-off.')
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('board', type=Path)
    parser.add_argument('--baseline', type=Path, required=True)
    parser.add_argument('--capture', action='store_true')
    parser.add_argument('--validate', action='store_true')
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    if args.capture and args.validate:
        parser.error('Capture and validation are separate operations')
    if args.capture:
        capture(args.board, args.baseline)
    elif args.validate:
        report = validate_policy(args.board, args.baseline)
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(json.dumps(report, indent=2)+'\n')
        print(json.dumps(report, indent=2))
        raise SystemExit(bool(report['errors']))
    else:
        check_protected(args.board, args.baseline)
        print('Protected placement, footprints, mechanics and graphics match')


if __name__ == '__main__':
    main()
